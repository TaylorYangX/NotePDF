"""Turn matched character spans into PDF markup annotations, the way Edge/Acrobat do.

One annotation per (match, page): a quad per text line, ``/C`` color, ``/CA`` opacity, the comment
in ``/Contents``, author in ``/T``, and an appearance stream generated by MuPDF so every viewer
draws the same thing. Each annotation's ``/NM`` starts with ``notepdf-`` so reruns can remove it.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from typing import Optional

import pymupdf

from .config import Style
from .matcher import Span
from .textindex import DocText

NM_PREFIX = "notepdf-"
POPUP_SIZE = (220, 110)
NOTE_ICON_SIZE = 20


@dataclass
class Placed:
    page: int  # 0-based
    xref: int
    nm: str
    lines: int
    comment: Optional[str]


def span_quads(doctext: DocText, span: Span) -> dict[int, list[pymupdf.Quad]]:
    """Quads per page for a span: one per text line (per character on non-horizontal lines)."""
    by_line: dict[tuple[int, int], list] = {}
    for ch in doctext.chars[span.start : span.end]:
        if ch.bbox is not None:
            by_line.setdefault((ch.page, ch.line), []).append(ch)
    quads: dict[int, list[pymupdf.Quad]] = {}
    for (page, _), chars in by_line.items():
        while chars and chars[-1].c.isspace():
            chars.pop()
        while chars and chars[0].c.isspace():
            chars.pop(0)
        if not chars:
            continue
        if chars[0].horizontal:
            rect = pymupdf.Rect(chars[0].bbox)
            for ch in chars[1:]:
                rect |= ch.bbox
            quads.setdefault(page, []).append(rect.quad)
        else:
            quads.setdefault(page, []).extend(pymupdf.Rect(ch.bbox).quad for ch in chars if not ch.c.isspace())
    return quads


def add_markup(
    doc: pymupdf.Document,
    page_no: int,
    quads: list[pymupdf.Quad],
    style: Style,
    comment: Optional[str],
    nm_seed: str,
) -> Placed:
    page = doc[page_no]
    adder = {
        "highlight": page.add_highlight_annot,
        "underline": page.add_underline_annot,
        "strikeout": page.add_strikeout_annot,
        "squiggly": page.add_squiggly_annot,
    }[style.type]
    annot = adder(quads)
    annot.set_colors(stroke=style.color)
    annot.set_opacity(style.opacity)
    _set_info(annot, style, comment)
    annot.update()
    nm = _tag(doc, annot.xref, nm_seed)

    # Quads are in unrotated page coordinates; place popups/notes in the margin the reader sees.
    anchor = quads[0].rect * page.rotation_matrix
    if comment and style.popup != "none":
        annot.set_popup(_margin_rect(page.rect, anchor.y0, *POPUP_SIZE))  # set_popup takes visible coordinates
        annot.set_open(style.popup == "open")
    if comment and style.sticky_note:
        _add_note(doc, page, anchor, style, comment, nm_seed)
    return Placed(page_no, annot.xref, nm, len(quads), comment)


def _set_info(annot: pymupdf.Annot, style: Style, comment: Optional[str]) -> None:
    now = pymupdf.get_pdf_now()
    info = {"subject": style.subject, "creationDate": now, "modDate": now}
    if comment:
        info["content"] = comment
    if style.author:
        info["title"] = style.author
    annot.set_info(**info)


def _add_note(doc, page: pymupdf.Page, anchor: pymupdf.Rect, style: Style, comment: str, nm_seed: str) -> None:
    vis = page.rect
    x = vis.x1 - NOTE_ICON_SIZE - 6
    if anchor.x1 > x:  # text runs into the margin; put the icon on the left instead
        x = vis.x0 + 6
    # add_text_annot works in unrotated coordinates; keep the icon box on the page.
    point = pymupdf.Point(x, anchor.y0) * page.derotation_matrix
    unrot = (vis * page.derotation_matrix).normalize()
    point = pymupdf.Point(
        min(max(point.x, unrot.x0), unrot.x1 - NOTE_ICON_SIZE),
        min(max(point.y, unrot.y0), unrot.y1 - NOTE_ICON_SIZE),
    )
    note = page.add_text_annot(point, comment, icon="Comment")
    note.set_colors(stroke=style.color)
    _set_info(note, style, comment)
    note.update()
    note.set_popup(_margin_rect(vis, anchor.y0, *POPUP_SIZE))
    note.set_open(False)
    _tag(doc, note.xref, nm_seed + ":note")


def _margin_rect(pr: pymupdf.Rect, y: float, w: float, h: float) -> pymupdf.Rect:
    x0 = max(pr.x0, pr.x1 - w - 10)
    y0 = min(max(pr.y0, y), pr.y1 - h)
    return pymupdf.Rect(x0, y0, x0 + w, y0 + h)


def _tag(doc: pymupdf.Document, xref: int, seed: str) -> str:
    nm = NM_PREFIX + hashlib.sha1(seed.encode("utf-8")).hexdigest()[:16]
    doc.xref_set_key(xref, "NM", pymupdf.get_pdf_str(nm))
    return nm


def is_notepdf(annot: pymupdf.Annot) -> bool:
    return (annot.info.get("id") or "").startswith(NM_PREFIX)


def remove_notepdf_annots(doc: pymupdf.Document) -> int:
    removed = 0
    for page in doc:
        for annot in [a for a in page.annots() if is_notepdf(a)]:
            page.delete_annot(annot)
            removed += 1
    return removed


def list_annots(doc: pymupdf.Document) -> list[dict]:
    rows = []
    for page in doc:
        for a in page.annots():
            if a.type[1] == "Popup":
                continue
            stroke = (a.colors or {}).get("stroke")
            rows.append(
                {
                    "page": page.number + 1,
                    "type": a.type[1],
                    "color": "#" + "".join(f"{round(c * 255):02X}" for c in stroke) if stroke else None,
                    "opacity": round(a.opacity, 3) if a.opacity is not None and a.opacity >= 0 else None,
                    "author": a.info.get("title") or None,
                    "comment": a.info.get("content") or None,
                    "text": _annot_text(page, a),
                    "id": a.info.get("id") or None,
                }
            )
    return rows


def _annot_text(page: pymupdf.Page, annot: pymupdf.Annot) -> Optional[str]:
    verts = annot.vertices
    if not verts or len(verts) < 4:
        return None
    parts = []
    for i in range(0, len(verts) - 3, 4):
        rect = pymupdf.Quad(verts[i : i + 4]).rect
        # Shrink vertically so neighbouring lines don't bleed in.
        rect.y0, rect.y1 = rect.y0 + rect.height * 0.3, rect.y1 - rect.height * 0.3
        parts.append(page.get_textbox(rect).strip())
    return " ".join(p for p in parts if p) or None

import json
import textwrap

import pymupdf
import pytest

from notepdf.cli import main
from notepdf.config import Config

from .conftest import build_pdf

TEX = r"""
\documentclass{article}
\usepackage{xcolor}
\definecolor{revcolor}{RGB}{0,0,255}
\newcommand{\rev}[1]{{\color{revcolor}#1}}
\newcommand{\ours}{OurNet}
\begin{document}
Deep models are popular. {\color{revcolor} %@note: R1.1 clarified motivation
We propose \ours, a method that is \emph{significantly} faster than prior work~\cite{a,b}.}
Unchanged text follows here.
%@note: R2.4 new experiment
\rev{We further evaluate on three new datasets.}
\input{sec}
\end{document}
"""
SEC = r"""
\textcolor{revcolor}{The first step encodes the input using a transformer
\begin{equation} y = f(x) \end{equation}}
"""
RENDERED = (
    "<p>Deep models are popular. <span style='color:#0000FF'>We propose OurNet, a method that is <i>significantly</i> "
    "faster than prior work [3, 7].</span> Unchanged text follows here. <span style='color:#0000FF'>We further "
    "evaluate on three new datasets.</span></p><p style='color:#0000FF'>The first step encodes the input using a "
    "transformer</p><p style='color:#0000FF'>y = f(x) (1)</p>"
)


@pytest.fixture
def project(tmp_path):
    (tmp_path / "paper.tex").write_text(textwrap.dedent(TEX))
    (tmp_path / "sec.tex").write_text(textwrap.dedent(SEC))
    build_pdf(tmp_path / "paper.pdf", [RENDERED])
    return tmp_path


def comments(pdf):
    with pymupdf.open(pdf) as doc:
        return [a.info["content"] or None for page in doc for a in page.annots() if a.type[1] == "Highlight"]


def test_tex_one_shot(project, capsys):
    out = project / "out.pdf"
    report = project / "report.json"
    code = main(["tex", str(project / "paper.tex"), str(project / "paper.pdf"), "-o", str(out), "--report", str(report), "--strict"])
    assert code == 0
    assert comments(out) == ["R1.1 clarified motivation", "R2.4 new experiment", None]
    printed = capsys.readouterr().out
    assert "3/3 entries matched" in printed and "sec.tex:3: display math (equation) is not highlighted" in printed
    data = json.loads(report.read_text())
    assert [e["status"] for e in data["entries"]] == ["found"] * 3
    assert data["entries"][2]["source"] == "sec.tex:2"


def test_tex2config_then_apply(project):
    cfg_path = project / "revisions.yaml"
    assert main(["tex2config", str(project / "paper.tex"), "--pdf", str(project / "paper.pdf"), "-o", str(cfg_path), "--highlight", "green", "--color", "revcolor"]) == 0
    text = cfg_path.read_text()
    assert text.startswith("# Generated by `notepdf tex2config`") and "display math" in text
    cfg = Config.load(cfg_path)
    assert cfg.input == project / "paper.pdf" and cfg.defaults.sequential and len(cfg.annotations) == 3
    assert cfg.annotations[0].comment == "R1.1 clarified motivation"

    # Users edit the generated file before applying it.
    cfg_path.write_text(text.replace("R2.4 new experiment", "'R2.4: added three datasets'"))
    out = project / "out.pdf"
    assert main(["apply", str(cfg_path), "-o", str(out)]) == 0
    assert comments(out) == ["R1.1 clarified motivation", "R2.4: added three datasets", None]
    with pymupdf.open(out) as doc:
        colors = {tuple(round(c, 2) for c in a.colors["stroke"]) for p in doc for a in p.annots() if a.type[1] == "Highlight"}
    assert colors == {(0.55, 0.76, 0.29)}  # "green"


def test_tex_with_config_file(project):
    cfg_path = project / "tex.yaml"
    cfg_path.write_text(
        "defaults:\n  author: Me\n  opacity: 0.3\n"
        "tex:\n  main: ignored.tex\n  markers:\n    - macro: rev\n      highlight: tex\n      comment: 'Revised #{n}'\n"
    )
    out = project / "out.pdf"
    assert main(["tex", str(project / "paper.tex"), str(project / "paper.pdf"), "-c", str(cfg_path), "-o", str(out)]) == 0
    with pymupdf.open(out) as doc:
        (annot,) = [a for p in doc for a in p.annots() if a.type[1] == "Highlight"]
        assert annot.info["content"] == "R2.4 new experiment" and annot.info["title"] == "Me"
        assert annot.colors["stroke"] == [0.0, 0.0, 1.0] and round(annot.opacity, 2) == 0.3


def test_strict_exit_code_and_errors(project, tmp_path, capsys):
    cfg = tmp_path / "c.yaml"
    cfg.write_text(f"input: {project / 'paper.pdf'}\nannotations:\n  - text: not in the document at all\n")
    assert main(["apply", str(cfg), "--dry-run"]) == 0
    assert main(["apply", str(cfg), "--dry-run", "--strict"]) == 1
    cfg.write_text("input: missing.pdf\nannotations:\n  - text: x\n")
    assert main(["apply", str(cfg)]) == 2
    assert "input PDF not found" in capsys.readouterr().err


def test_list_and_clear(project, capsys):
    out = project / "out.pdf"
    main(["tex", str(project / "paper.tex"), str(project / "paper.pdf"), "-o", str(out)])
    capsys.readouterr()
    assert main(["list", str(out), "--json"]) == 0
    rows = json.loads(capsys.readouterr().out)
    assert len(rows) == 3 and rows[0]["comment"] == "R1.1 clarified motivation"
    cleaned = project / "clean.pdf"
    assert main(["clear", str(out), "-o", str(cleaned)]) == 0
    assert comments(cleaned) == []
    assert main(["clear", str(out)]) == 0  # in place
    assert comments(out) == []
